"""Compare human review labels with BOWEN's positioning deviation (run AFTER reviewers finish; labels are never
generated by a model).

Input
  results/bowen_review/labels.json  exported from the review page's store (reviews/<reviewer>/items/<item>), shaped
                                    {"<reviewer>": {"<item>": {situation, assignment, alternatives, quality,
                                    uncertainty, ...}}}; Claude exports it with the ArtifactData tool, or reviewers
                                    paste "Copy my labels" output as {"<reviewer>": <that labels object>}
  results/bowen_review/key.json     private key (BOWEN deviation, stratum, situation) written by bowen_review.py
Analyses (reported overall, by situation, and excluding high-uncertainty labels)
  agreement     inter-rater: quality (Krippendorff's alpha, interval), assignment (% exact agreement)
  validity      Spearman between mean human quality and -deviation; AUC of deviation for breakdowns (quality <= 2)
                vs the rest; mean deviation where reviewers ticked an acceptable alternative the defender used
                (alternative instead of error)
  strata        mean human quality by BOWEN deviation tertile (low / ordinary / high)
Interpretation rule (fixed before labels exist): BOWEN deviation may be called "execution quality" only if
Spearman(quality, -deviation) > 0 with a 95% bootstrap CI above 0 AND the breakdown AUC CI is above 0.5, overall and
in at least three of the four situations. Otherwise it stays "positioning deviation".
Output: results/bowen_review/comparison.json     python bowen_review_compare.py
"""
import json
from collections import defaultdict
import numpy as np
from scipy.stats import spearmanr

from masked_paths import ROOT

D = ROOT / 'results/bowen_review'


def kalpha_interval(mat):
    """Krippendorff's alpha, interval metric; mat: items x raters with np.nan for missing."""
    vals = [row[~np.isnan(row)] for row in mat]; vals = [v for v in vals if len(v) >= 2]
    if not vals:
        return None
    allv = np.concatenate(vals); n = len(allv)
    do = sum(((v[:, None] - v[None, :]) ** 2).sum() / (len(v) - 1) for v in vals) / n
    de = ((allv[:, None] - allv[None, :]) ** 2).sum() / (n * (n - 1))
    return float(1 - do / de) if de > 0 else None


def auc(score, pos):
    s, p = np.asarray(score), np.asarray(pos, bool)
    if p.sum() == 0 or (~p).sum() == 0:
        return None
    r = np.argsort(np.argsort(s)) + 1
    return float((r[p].sum() - p.sum() * (p.sum() + 1) / 2) / (p.sum() * (~p).sum()))


def main():
    L = json.load(open(D / 'labels.json')); K = json.load(open(D / 'key.json'))['items']
    raters = sorted(L); items = sorted(K)
    Q = np.full((len(items), len(raters)), np.nan)
    for j, r in enumerate(raters):
        for i, it in enumerate(items):
            v = L[r].get(it)
            if v and v.get('quality') and v.get('uncertainty') != 'High':
                Q[i, j] = float(v['quality'])
    res = dict(raters=len(raters), items_labelled=int((~np.isnan(Q)).any(1).sum()))
    res['quality_alpha'] = kalpha_interval(Q)
    asg = defaultdict(list)
    for r in raters:
        for it, v in L[r].items():
            if v.get('assignment'):
                asg[it].append(v['assignment'])
    multi = [a for a in asg.values() if len(a) >= 2]
    res['assignment_exact_agreement'] = float(np.mean([len(set(a)) == 1 for a in multi])) if multi else None
    mq = np.nanmean(Q, 1); ok = ~np.isnan(mq)
    dev = np.array([K[it]['mean_deviation_ft'] for it in items]); sit = np.array([K[it]['situation'] for it in items])
    strat = np.array([K[it]['stratum'] for it in items])
    rng = np.random.default_rng(0)

    def validity(mask):
        m = mask & ok
        if m.sum() < 8:
            return dict(n=int(m.sum()))
        rho = spearmanr(mq[m], -dev[m]).correlation
        bs = []
        idx = np.flatnonzero(m)
        for _ in range(2000):
            b = rng.choice(idx, len(idx))
            if np.unique(mq[b]).size > 1:
                bs.append(spearmanr(mq[b], -dev[b]).correlation)
        a = auc(dev[m], mq[m] <= 2)
        ba = [auc(dev[b], mq[b] <= 2) for b in (rng.choice(idx, len(idx)) for _ in range(2000))]
        ba = [x for x in ba if x is not None]
        return dict(n=int(m.sum()), spearman_quality_vs_neg_deviation=round(float(rho), 3),
                    ci=np.percentile(bs, [2.5, 97.5]).round(3).tolist() if bs else None,
                    breakdown_auc=None if a is None else round(a, 3),
                    auc_ci=np.percentile(ba, [2.5, 97.5]).round(3).tolist() if ba else None)
    res['validity_overall'] = validity(np.ones(len(items), bool))
    res['validity_by_situation'] = {s: validity(sit == s) for s in sorted(set(sit))}
    res['quality_by_deviation_tertile'] = {s: round(float(np.nanmean(mq[strat == s])), 2) if (ok & (strat == s)).any() else None
                                          for s in ('low', 'ordinary', 'high', 'random')}
    vo = res['validity_overall']; bysit = res['validity_by_situation']
    passes = lambda v: v.get('ci') and v['ci'][0] > 0 and v.get('auc_ci') and v['auc_ci'][0] > 0.5
    res['execution_quality_label_justified'] = bool(passes(vo) and sum(passes(v) for v in bysit.values()) >= 3)
    json.dump(res, open(D / 'comparison.json', 'w'), indent=1)
    print(json.dumps(res, indent=1))


if __name__ == '__main__':
    main()
